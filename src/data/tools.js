// Convenience lookup helpers -------------------------------------------------
// Every helper takes an optional `tools` array (defaulting to the static,
// verified TOOLS list above) so the same functions also work with the
// merged [static + admin-added-via-Firestore] list produced by
// `useAllTools()` in src/hooks/useAllTools.js — nothing here needs to
// change just because the directory can now grow at runtime.
export const getToolById = (id, tools = TOOLS) => tools.find((t) => t.id === id)
export const getToolsByCategory = (categoryId, tools = TOOLS) => tools.filter((t) => t.category === categoryId)
export const getFeaturedTools = (tools = TOOLS) => tools.filter((t) => t.featured)
export const getFreeTools = (tools = TOOLS) => tools.filter((t) => t.pricing === 'Free' || t.pricing === 'Freemium')
export const getStudentTools = (tools = TOOLS) => tools.filter((t) => t.studentRecommended)
export const getRecentTools = (count = 8, tools = TOOLS) =>
  [...tools].sort((a, b) => new Date(b.dateAdded) - new Date(a.dateAdded)).slice(0, count)
export const getPopularTools = (count = 8, tools = TOOLS) =>
  [...tools].sort((a, b) => b.popularity - a.popularity).slice(0, count)
